/**
 * Checks whether a URL is a real link (not a placeholder).
 */
function isValidUrl(url) {
  if (!url) return false;
  const placeholders = ['YOUR_', 'PLACEHOLDER', '#', ''];
  return !placeholders.some((p) => url.toUpperCase().startsWith(p));
}

export default function SocialLinks({ className = '' }) {
  const validLinks = socialLinks.filter((link) => isValidUrl(link.url));
  if (validLinks.length === 0) return null;

  return (
    <div className={`social-links ${className}`}>
      {validLinks.map((link) => (
        <a
          key={link.platform}
          href={link.url}
          target="_blank"
          rel="noopener noreferrer"
          className="social-link"
          aria-label={link.platform}
          title={link.platform}
        >
          {icons[link.icon] || link.platform[0]}
        </a>
      ))}
    </div>
  );
}

